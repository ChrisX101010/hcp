    #[test]
    fn generated_sbox_matches_fips197_exactly() {
        let t = sbox_table();
        for i in 0..256usize {
            assert_eq!(
                t[i], FIPS197_SBOX[i],
                "S-box mismatch at {:#04x}: generated {:#04x}, FIPS-197 {:#04x}",
                i, t[i], FIPS197_SBOX[i]
            );
        }
    }

    #[test]
    fn sbox_is_a_bijection() {
        let t = sbox_table();
        let mut seen = [false; 256];
        for &v in t.iter() {
            assert!(!seen[v as usize], "S-box must be a permutation");
            seen[v as usize] = true;
        }
    }

    #[test]
    fn gf_inverse_is_a_true_inverse() {
        assert_eq!(gf_inv(0), 0);
        for a in 1u16..256 {
            let a = a as u8;
            assert_eq!(gf_mul(a, gf_inv(a)), 1, "inverse failed for {:#04x}", a);
        }
    }

    #[test]
    fn gf_mul_basic_identities() {
        assert_eq!(gf_mul(0x57, 0x01), 0x57);
        assert_eq!(gf_mul(0x57, 0x13), 0xfe); // FIPS-197 section 4.2 example
        assert_eq!(gf_mul(0x00, 0xff), 0x00);
    }
