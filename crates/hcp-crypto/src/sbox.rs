//! AES S-box, *generated* from the GF(2^8) field rather than pasted as a table.
//!
//! The S-box is the composition of two maps over GF(2^8) (modulus 0x11B):
//!   1. multiplicative inverse (with 0 -> 0), then
//!   2. the affine transform
//!      `b = inv ^ rotl(inv,1) ^ rotl(inv,2) ^ rotl(inv,3) ^ rotl(inv,4) ^ 0x63`
//!
//! This mirrors how `hcp-ecc` derives parity-bit positions arithmetically
//! instead of hard-coding them: the hardware stays first-principles, and the
//! test suite re-derives every byte independently.

/// Multiply two bytes in GF(2^8) with the AES reduction polynomial 0x11B.
pub fn gf_mul(mut a: u8, mut b: u8) -> u8 {
    let mut p: u8 = 0;
    for _ in 0..8 {
        if b & 1 != 0 {
            p ^= a;
        }
        let hi = a & 0x80;
        a <<= 1;
        if hi != 0 {
            a ^= 0x1b;
        }
        b >>= 1;
    }
    p
}

/// Multiplicative inverse in GF(2^8). AES defines the inverse of 0 as 0.
///
/// Uses `a^254 == a^-1` in the multiplicative group (order 255), computed by
/// square-and-multiply: 8 squarings instead of a 256-entry search.
pub fn gf_inv(a: u8) -> u8 {
    if a == 0 {
        return 0;
    }
    let mut result: u8 = 1;
    let mut base = a;
    let mut exp = 254u32;
    while exp > 0 {
        if exp & 1 == 1 {
            result = gf_mul(result, base);
        }
        base = gf_mul(base, base);
        exp >>= 1;
    }
    result
}

/// Single S-box entry.
pub fn sbox_byte(a: u8) -> u8 {
    let inv = gf_inv(a);
    inv ^ inv.rotate_left(1) ^ inv.rotate_left(2) ^ inv.rotate_left(3) ^ inv.rotate_left(4) ^ 0x63
}

/// Full 256-entry S-box.
pub fn sbox_table() -> [u8; 256] {
    let mut t = [0u8; 256];
    for (i, e) in t.iter_mut().enumerate() {
        *e = sbox_byte(i as u8);
    }
    t
}

